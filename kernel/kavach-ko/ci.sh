#!/usr/bin/env bash
# SPDX-License-Identifier: GPL-2.0-only
#
# Build and exercise kavach.ko where it can be done safely: a Rust-enabled kernel built from
# source and booted in a throwaway VM (virtme-ng / QEMU). The module is never loaded into the
# machine running this script. Used by .github/workflows/kavach-ko.yml (manual trigger only);
# works the same on a developer machine that has the tools below.
#
# Usage:
#   kernel/kavach-ko/ci.sh deps                 install build deps (Ubuntu, uses sudo; CI only)
#   kernel/kavach-ko/ci.sh kernel [--fuzz]      fetch + configure + build the kernel
#   kernel/kavach-ko/ci.sh module               build kavach.ko against it, check its BTF
#   kernel/kavach-ko/ci.sh selftest             boot it; selftest.py + the bpf suite with the module
#   kernel/kavach-ko/ci.sh syz MINUTES          (after `kernel --fuzz`) run syzkaller for MINUTES
#
# `kernel` builds a minimal virtme-ng config plus CONFIG_RUST and everything Kavach needs.
# `kernel --fuzz` builds a separate tree for syzkaller: KASAN + KCOV, and kavach.ko linked INTO
# vmlinux (drivers/kavach), because syzkaller resolves kfunc BTF ids from vmlinux BTF only (see
# syz/kavach.txt).
#
# Environment:
#   KAVACH_KO_WORK     work directory (default target/kavach-ko)
#   KAVACH_KO_KERNEL   kernel tag from the stable tree (default v7.1.9)
#   SYZKALLER_COMMIT   syzkaller revision (default: the one syz/kavach.txt was validated with)
#   VNG                virtme-ng command (default vng)
set -euo pipefail

SELF=$(readlink -f "$0")
HERE=$(dirname "$SELF")
ROOT=$(readlink -f "$HERE/../..")
WORK=$(mkdir -p "${KAVACH_KO_WORK:-$ROOT/target/kavach-ko}" && readlink -f "${KAVACH_KO_WORK:-$ROOT/target/kavach-ko}")
TAG=${KAVACH_KO_KERNEL:-v7.1.9}
SYZKALLER_COMMIT=${SYZKALLER_COMMIT:-9a575fe511f5d38ab3d9b6977ffabb567c3927f0}
BINDGEN_VERSION=0.72.1
STABLE=https://git.kernel.org/pub/scm/linux/kernel/git/stable/linux.git
VNG=${VNG:-vng}
JOBS=$(nproc)

die() { echo "kavach-ko: error: $*" >&2; exit 1; }
log() { echo "kavach-ko: $*" >&2; }

ksrc() { echo "$WORK/linux-$TAG${1:+-$1}"; }

deps() {
	sudo apt-get update -qq
	sudo apt-get install -y -qq --no-install-recommends build-essential bc bison flex cpio \
		libelf-dev libssl-dev dwarves clang lld llvm rsync python3 kmod
	rustup component add rust-src
	command -v bindgen >/dev/null || cargo install --locked bindgen-cli --version "$BINDGEN_VERSION"
}

# Options every Kavach kernel needs (BPF, BTF incl. modules, BPF-LSM, TC, cgroup hooks, Rust).
kavach_options() {
	cat <<-'EOF'
	RUST=y
	MODULES=y
	BPF=y
	BPF_SYSCALL=y
	BPF_JIT=y
	BPF_LSM=y
	DEBUG_INFO=y
	DEBUG_INFO_DWARF5=y
	DEBUG_INFO_BTF=y
	DEBUG_INFO_BTF_MODULES=y
	SECURITY=y
	SECURITYFS=y
	NET_CLS_BPF=y
	NET_SCH_INGRESS=y
	NET_CLS_ACT=y
	CGROUPS=y
	CGROUP_BPF=y
	XDP_SOCKETS=y
	VETH=y
	DUMMY=y
	BPF_EVENTS=y
	FTRACE=y
	EOF
}

fuzz_options() {
	cat <<-'EOF'
	KASAN=y
	KASAN_INLINE=y
	KCOV=y
	KCOV_INSTRUMENT_ALL=y
	KCOV_ENABLE_COMPARISONS=y
	DEBUG_FS=y
	CONFIGFS_FS=y
	KALLSYMS=y
	KALLSYMS_ALL=y
	DEBUG_KMEMLEAK=n
	FAULT_INJECTION=y
	FAULT_INJECTION_DEBUG_FS=y
	FAILSLAB=y
	E1000=y
	VIRTIO_NET=y
	VIRTIO_BLK=y
	EXT4_FS=y
	BINFMT_MISC=y
	EOF
}

apply_options() {
	local tree=$1 kv
	shift
	while read -r kv; do
		case "$kv" in
			*=n) "$tree/scripts/config" --file "$tree/.config" -d "${kv%=n}" ;;
			*) "$tree/scripts/config" --file "$tree/.config" -e "${kv%=y}" ;;
		esac
	done
	"$tree/scripts/config" --file "$tree/.config" \
		--set-str LSM "landlock,lockdown,yama,integrity,bpf"
}

# Link kavach.ko into vmlinux (fuzz kernels only).
builtin_kavach() {
	local tree=$1 dst=$1/drivers/kavach
	rm -rf "$dst"
	mkdir -p "$dst"
	cp "$HERE/kavach_ko.rs" "$HERE/kavach_kfunc.c" "$ROOT/bpf/include/kavach_kfunc.h" "$dst/"
	"$HERE/vendor.sh" >"$dst/kavach_vendor.rs"
	cat >"$dst/Makefile" <<-'EOF'
	# SPDX-License-Identifier: GPL-2.0-only
	# Generated by kernel/kavach-ko/ci.sh: kavach.ko built into vmlinux for syzkaller.
	obj-$(CONFIG_RUST) += kavach.o
	kavach-y := kavach_ko.o kavach_kfunc.o
	ccflags-y += -I$(src)
	EOF
	grep -q 'kavach/' "$tree/drivers/Makefile" || echo 'obj-y += kavach/' >>"$tree/drivers/Makefile"
}

kernel() {
	local fuzz=${1:-} tree
	tree=$(ksrc "${fuzz:+fuzz}")
	if [ ! -f "$tree/Makefile" ]; then
		log "cloning $TAG"
		git clone -q --depth 1 --branch "$TAG" "$STABLE" "$tree"
	fi
	cd "$tree"
	make LLVM=1 rustavailable || die "this Rust toolchain cannot build $TAG (see above)"
	if [ -n "$fuzz" ]; then
		make LLVM=1 defconfig kvm_guest.config >/dev/null
		{ kavach_options; fuzz_options; } | apply_options "$tree"
		builtin_kavach "$tree"
	else
		command -v "${VNG%% *}" >/dev/null || die "virtme-ng ('$VNG') not found"
		$VNG --kconfig >/dev/null
		kavach_options | apply_options "$tree"
	fi
	make LLVM=1 olddefconfig >/dev/null
	local opt
	for opt in RUST DEBUG_INFO_BTF BPF_LSM ${fuzz:+KASAN KCOV}; do
		grep -q "^CONFIG_$opt=y" .config || die "CONFIG_$opt did not survive olddefconfig"
	done
	log "building $tree ($JOBS jobs)"
	make LLVM=1 -j"$JOBS" >/dev/null
	if [ -n "$fuzz" ]; then
		grep -q ' kavach_evaluate$' System.map || die "kavach_evaluate is not in vmlinux"
	fi
	log "kernel ready: $tree"
}

module() {
	local tree
	tree=$(ksrc)
	[ -f "$tree/vmlinux" ] || die "build the kernel first: $SELF kernel"
	make -C "$HERE" KDIR="$tree" LLVM=1
	local ko=$HERE/kavach.ko
	modinfo "$ko"
	# The verifier binds the kfunc through the module's BTF: it must have a FUNC record.
	command -v bpftool >/dev/null || die "bpftool not found"
	bpftool btf dump file "$ko" base "$tree/vmlinux" | grep -q "FUNC 'kavach_evaluate'" ||
		die "kavach.ko has no BTF FUNC record for kavach_evaluate"
	log "built $ko"
}

# Inside the VM (root): the differential self-test, then the privileged suite with the module.
guest() {
	local obj=$1 ko=$2 bin=$3 out=$4 rc=0
	{
		echo "guest kernel: $(uname -r)"
		mountpoint -q /sys/fs/bpf || mount -t bpf bpf /sys/fs/bpf
		mountpoint -q /sys/kernel/security || mount -t securityfs securityfs /sys/kernel/security
		python3 "$HERE/selftest.py" "$obj" "$ko" 5 || rc=1
		if [ "$rc" = 0 ]; then
			insmod "$ko"
			[ -e /sys/kernel/btf/kavach ] || { echo "kavach.ko loaded but has no BTF"; rc=1; }
			"$ROOT/scripts/kernel-matrix.sh" guest "$bin" "$out" || true
			rc=$(cat "$out/rc" 2>/dev/null || echo 1)
		fi
		echo "$rc" >"$out/rc"
	} 2>&1 | tee "$out/kavach-ko.log"
}

selftest() {
	local tree obj bin out kvm=()
	tree=$(ksrc)
	[ -f "$HERE/kavach.ko" ] || die "build the module first: $SELF module"
	(cd "$ROOT" && cargo xtask build-bpf)
	obj=$ROOT/target/bpf/kavach.bpf.o
	bin=$("$ROOT/scripts/kernel-matrix.sh" build)
	out=$WORK/results
	rm -rf "$out"
	mkdir -p "$out"
	[ -r /dev/kvm ] && [ -w /dev/kvm ] || kvm=(--disable-kvm)
	set +e
	timeout --foreground -k 30 1800 $VNG --run "$tree" --user root "${kvm[@]}" \
		--memory 2G --cpus 2 --rwdir "$out" --append "lsm=yama,bpf" --disable-microvm \
		--exec "$SELF guest '$obj' '$HERE/kavach.ko' '$bin' '$out'" </dev/null >"$out/console.log" 2>&1
	set -e
	[ -f "$out/rc" ] || { tail -n 60 "$out/console.log" >&2; die "the guest never reported a result"; }
	cat "$out/kavach-ko.log" >&2
	[ "$(cat "$out/rc")" = 0 ] || die "kavach.ko checks failed in the VM"
	log "selftest + bpf suite with kavach.ko: PASS"
}

syz() {
	local minutes=${1:?minutes} tree syzdir img cfg crashes
	tree=$(ksrc fuzz)
	[ -f "$tree/arch/x86/boot/bzImage" ] || die "build the fuzz kernel first: $SELF kernel --fuzz"
	command -v go >/dev/null || die "go not found"
	syzdir=$WORK/syzkaller
	if [ ! -d "$syzdir/.git" ]; then
		git clone -q https://github.com/google/syzkaller.git "$syzdir"
	fi
	git -C "$syzdir" fetch -q origin "$SYZKALLER_COMMIT" 2>/dev/null || true
	git -C "$syzdir" checkout -q "$SYZKALLER_COMMIT"
	cp "$HERE/syz/kavach.txt" "$HERE/syz/kavach.txt.const" "$syzdir/sys/linux/"
	make -C "$syzdir" descriptions >/dev/null
	make -C "$syzdir" -j"$JOBS" TARGETOS=linux TARGETARCH=amd64 >/dev/null
	img=$WORK/image
	if [ ! -f "$img/trixie.img" ]; then
		mkdir -p "$img"
		(cd "$img" && sudo apt-get install -y -qq debootstrap &&
			sudo "$syzdir/tools/create-image.sh" --distribution trixie --feature minimal &&
			sudo chown "$(id -u):$(id -g)" trixie.img trixie.id_rsa)
	fi
	cfg=$WORK/syz-manager.cfg
	sed -e "s|@WORKDIR@|$WORK/syz-workdir|; s|@KSRC@|$tree|g; s|@IMAGE@|$img/trixie.img|" \
		-e "s|@SSHKEY@|$img/trixie.id_rsa|; s|@SYZKALLER@|$syzdir|; s|@VMS@|${SYZ_VMS:-2}|" \
		"$HERE/syz/syz-manager.cfg.in" >"$cfg"
	mkdir -p "$WORK/syz-workdir"
	log "fuzzing for $minutes minutes"
	timeout --foreground -s INT "$((minutes * 60))" "$syzdir/bin/syz-manager" -config "$cfg" || true
	crashes=$WORK/syz-workdir/crashes
	if [ -d "$crashes" ] && [ -n "$(ls -A "$crashes")" ]; then
		for d in "$crashes"/*; do echo "crash: $(head -1 "$d/description")"; done
		die "syzkaller found crashes (see $crashes)"
	fi
	log "no crashes in $minutes minutes"
}

case "${1:-}" in
	deps) deps ;;
	kernel) kernel "$([ "${2:-}" = --fuzz ] && echo fuzz)" ;;
	module) module ;;
	selftest) selftest ;;
	guest) shift && guest "$@" ;;
	syz) syz "${2:-}" ;;
	*) sed -n '3,/^set -euo/p' "$SELF" | sed '$d; s/^# \{0,1\}//'; exit 2 ;;
esac
