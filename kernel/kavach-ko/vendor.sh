#!/bin/sh
# SPDX-License-Identifier: GPL-2.0-only
#
# Print kavach_vendor.rs: kavach-common (abi, addr) and kavach-core as inline modules of the
# kernel crate.
#
# Kbuild compiles each Rust object with one `rustc` call against the kernel's own `core` and
# `kernel` crates: no cargo, no crates.io, no proc macros. Both crates are already `#![no_std]`
# with no `alloc`, so they need only two mechanical changes:
#   * the bytemuck derives (`Pod`, `Zeroable`), `use bytemuck` and `impl Default for Policy`
#     (which is `Zeroable::zeroed()`) are dropped: the module never builds or casts these
#     structs, it only reads them through references;
#   * crate paths are rewritten (`crate::abi` -> `super::abi`, `kavach_common::` ->
#     `super::kavach_common::`), and crate-level attributes / the out-of-line test module go.
# The result is checked so a new dependency in those crates fails here, loudly, instead of
# producing a module that silently diverges from user space.
set -eu

here=$(cd "$(dirname "$0")" && pwd)
root=${KAVACH_SRC:-$here/../..}
common=$root/crates/kavach-common/src
core=$root/crates/kavach-core/src

for f in "$common/abi.rs" "$common/addr.rs" "$core/lib.rs"; do
	[ -f "$f" ] || { echo "vendor.sh: missing $f" >&2; exit 1; }
done

strip_bytemuck() {
	sed -E \
		-e '/^use bytemuck::/d' \
		-e '/^impl Default for Policy \{/,/^\}/d' \
		-e '/#\[derive\(/{s/, *Pod\b//; s/, *Zeroable\b//; s/\bPod, *//; s/\bZeroable, *//}' \
		-e 's/\bcrate::/super::/g' \
		"$1"
}

out=$(
	cat <<'EOF'
// SPDX-License-Identifier: GPL-2.0-only
// @generated by kernel/kavach-ko/vendor.sh from crates/kavach-common and crates/kavach-core.
// DO NOT EDIT: change the crates and rebuild.

/// `kavach-common`: the C <-> Rust ABI (`abi`) and address helpers (`addr`).
pub(crate) mod kavach_common {
    pub(crate) mod abi {
EOF
	strip_bytemuck "$common/abi.rs"
	cat <<'EOF'
    }
    pub(crate) mod addr {
EOF
	strip_bytemuck "$common/addr.rs"
	cat <<'EOF'
    }
    #[allow(unused_imports)]
    pub(crate) use abi::*;
}

/// `kavach-core`: the reference evaluator, unchanged.
pub(crate) mod kavach_core {
EOF
	sed -E \
		-e '/^#!\[no_std\]/d' \
		-e '/^#\[cfg\(test\)\]$/{N;/\nmod tests;$/d}' \
		-e 's/\bkavach_common::/super::kavach_common::/g' \
		"$core/lib.rs"
	cat <<'EOF'
}
EOF
)

# Anything the kernel build cannot satisfy must not slip through.
if printf '%s\n' "$out" | grep -nE '\bbytemuck\b|\bPod\b|\bZeroable\b|extern crate|\bstd::|\balloc::|^mod tests;' |
	grep -vE '^[0-9]+:\s*//' | grep -vE '#\[cfg\((test|feature = "std")\)\]' >&2; then
	echo "vendor.sh: the crates use something the kernel build cannot provide (see above)" >&2
	exit 1
fi

printf '%s\n' "$out"
